from __future__ import annotations

import json
from dataclasses import dataclass, field
from typing import Any


def _normalize_prop_name(name: str) -> str:
    return name[:-1] if name.endswith("_") else name


def _flatten_children(children: Any) -> list[Any]:
    flattened: list[Any] = []
    for child in children:
        if child is None:
            continue
        if isinstance(child, (list, tuple)):
            flattened.extend(_flatten_children(child))
            continue
        flattened.append(child)
    return flattened


@dataclass(frozen=True)
class PortRef:
    component_name: str
    port_name: str

    def to_selector(self) -> str:
        return f".{self.component_name} > .{self.port_name}"

    def __str__(self) -> str:
        return self.to_selector()


@dataclass
class Element:
    tag: str
    props: dict[str, Any] = field(default_factory=dict)
    children: list[Any] = field(default_factory=list)

    def __getattr__(self, name: str) -> PortRef:
        if name.startswith("_"):
            raise AttributeError(name)

        component_name = self.props.get("name")
        if not component_name:
            raise AttributeError(
                f"Cannot resolve port '{name}' on <{self.tag}> without a name prop"
            )

        return PortRef(str(component_name), name)

    def to_tsx(self, indent: int = 0) -> str:
        return render_element(self, indent)


class Circuit:
    def __init__(self, *elements: Any) -> None:
        self.elements: list[Any] = []
        self.add(*elements)

    def add(self, *elements: Any) -> "Circuit":
        self.elements.extend(_flatten_children(elements))
        return self

    def to_tsx(self) -> str:
        lines = [
            "// Generated by pycircuit.",
            "// Do not edit by hand; update the Python source instead.",
            "",
            "export default () => (",
        ]

        if len(self.elements) == 1:
            lines.append(render_node(self.elements[0], 2))
        else:
            lines.append("  <>")
            for element in self.elements:
                lines.append(render_node(element, 4))
            lines.append("  </>")

        lines.append(")")
        return "\n".join(lines).rstrip() + "\n"


def create_element(
    tag: str, *elements: Any, children: Any = None, **props: Any
) -> Element:
    normalized_props = {
        _normalize_prop_name(key): value
        for key, value in props.items()
        if value is not None
    }
    return Element(
        tag=tag,
        props=normalized_props,
        children=_flatten_children([*elements, children]),
    )


def _serialize_js_value(value: Any) -> str:
    if isinstance(value, PortRef):
        return json.dumps(value.to_selector(), ensure_ascii=True)

    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=True)

    if value is True:
        return "true"

    if value is False:
        return "false"

    if value is None:
        return "null"

    if isinstance(value, (int, float)):
        return repr(value)

    if isinstance(value, dict):
        items = [
            f"{json.dumps(_normalize_prop_name(str(key)), ensure_ascii=True)}: {_serialize_js_value(item)}"
            for key, item in value.items()
        ]
        return "{ " + ", ".join(items) + " }" if items else "{}"

    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_serialize_js_value(item) for item in value) + "]"

    raise TypeError(f"Unsupported prop value for TSX serialization: {value!r}")


def _serialize_prop(name: str, value: Any) -> str:
    normalized_name = _normalize_prop_name(name)
    if isinstance(value, (str, PortRef)):
        return f"{normalized_name}={_serialize_js_value(value)}"
    return f"{normalized_name}={{{_serialize_js_value(value)}}}"


def render_node(value: Any, indent: int = 0) -> str:
    space = " " * indent

    if isinstance(value, Element):
        return render_element(value, indent)

    if isinstance(value, PortRef):
        return f"{space}{{{_serialize_js_value(value)}}}"

    if isinstance(value, str):
        return f"{space}{{{json.dumps(value, ensure_ascii=True)}}}"

    raise TypeError(f"Unsupported child node for TSX serialization: {value!r}")


def render_element(element: Element, indent: int = 0) -> str:
    space = " " * indent
    props = " ".join(
        _serialize_prop(name, value) for name, value in element.props.items()
    )
    props_suffix = f" {props}" if props else ""

    if not element.children:
        return f"{space}<{element.tag}{props_suffix} />"

    lines = [f"{space}<{element.tag}{props_suffix}>"]
    for child in element.children:
        lines.append(render_node(child, indent + 2))
    lines.append(f"{space}</{element.tag}>")
    return "\n".join(lines)


def render_to_tsx(value: Any) -> str:
    if isinstance(value, Circuit):
        return value.to_tsx()

    if isinstance(value, Element):
        return Circuit(value).to_tsx()

    if isinstance(value, (list, tuple)):
        return Circuit(*value).to_tsx()

    raise TypeError(
        "Expected a Circuit, Element, or list/tuple of Elements when rendering TSX"
    )


render = render_to_tsx

__all__ = [
    "Circuit",
    "Element",
    "PortRef",
    "create_element",
    "render",
    "render_to_tsx",
]
