const renderPythonReadme = ({ propsVersion }: { propsVersion: string }) => `\
# pycircuits

Generated Python bindings for tscircuit components from \`@tscircuit/props@${propsVersion}\`.

\`\`\`python
from pycircuits import Circuit, board, led, resistor, trace

led1 = led(name="LED1", color="red", footprint="0603", pcbY=4)
r1 = resistor(name="R1", resistance="1k", footprint="0603", pcbY=-4)

circuit = Circuit(
    board(
        width="12mm",
        height="20mm",
        children=[
            led1,
            r1,
            trace(from_=r1.pin2, to=led1.anode),
            trace(from_=r1.pin1, to="net.VCC"),
            trace(from_=led1.cathode, to="net.GND"),
        ],
    )
)
\`\`\`
`;

const renderMetadataJson = ({
  components,
  propsVersion,
}: {
  components: PropComponent[];
  propsVersion: string;
}) =>
  JSON.stringify(
    {
      componentCount: components.length,
      components: components.map((component) => component.tagName),
      propsVersion,
    },
    null,
    2,
  );

export const renderPythonLibraryFiles = ({
  components,
  propsVersion,
}: {
  components: PropComponent[];
  propsVersion: string;
}) => ({
  "__init__.py": renderPythonInit(components),
  "components.py": renderPythonComponents(components),
  "py.typed": "",
  "runtime.py": renderPythonRuntime(),
  "../METADATA.json": renderMetadataJson({ components, propsVersion }),
  "../pyproject.toml": renderPythonProjectToml({ propsVersion }),
  "../README.md": renderPythonReadme({ propsVersion }),
});
