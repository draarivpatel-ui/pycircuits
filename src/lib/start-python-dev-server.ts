import fs from "node:fs/promises";
import net from "node:net";
import path from "node:path";
// The published package exports DevServer from the "./lib" subpath.
import { DevServer } from "@tscircuit/cli/lib";
import { DEFAULT_ENTRYPOINTS, renderPythonCircuit } from "./build-python-circuit";
import { generatePythonLibrary } from "./generate-python-library";

const DEFAULT_START_TARGET = "examples";
const DEFAULT_DEV_SERVER_PORT = 3020;
const LEGACY_GENERATED_TSX_FILENAME = "generated.circuit.tsx";
const PYTHON_SCAN_INTERVAL_MS = 250;
const REBUILD_DEBOUNCE_MS = 150;

type StartTarget = {
  entryFilePaths: string[];
  projectDir: string;
  watchRoot: string;
};

type SyncedGeneratedCircuit = {
  entryFilePath: string;
  generatedTsxPath: string;
  selectedSymbol: string;
};

export type StartPythonDevServerOptions = {
  cwd?: string;
  inputPath?: string;
  port?: number;
};

export type PythonDevServerHandle = {
  componentFilePath: string;
  port: number;
  projectDir: string;
  stop: () => Promise<void>;
};

const fileExists = async (filePath: string) => {
  try {
    await fs.access(filePath);
    return true;
  } catch {
    return false;
  }
};

const findProjectRoot = async (startPath: string) => {
  let currentPath = startPath;

  while (true) {
    if (await fileExists(path.join(currentPath, "package.json"))) {
      return currentPath;
    }

    const parentPath = path.dirname(currentPath);
    if (parentPath === currentPath) {
      return startPath;
    }

    currentPath = parentPath;
  }
};

const shouldSkipDirectory = (directoryName: string) =>
  directoryName.startsWith(".") ||
  directoryName === "__pycache__" ||
  directoryName === "dist" ||
  directoryName === "generated" ||
  directoryName === "node_modules";

const getRelativePath = (filePath: string, cwd = process.cwd()) =>
  path.relative(cwd, filePath) || ".";

const getGeneratedTsxPath = (entryFilePath: string) =>
  `${entryFilePath}.tsx`;

const getLegacyGeneratedTsxPath = (entryFilePath: string) =>
  path.join(path.dirname(entryFilePath), LEGACY_GENERATED_TSX_FILENAME);

const writeTextFileIfChanged = async (filePath: string, textContent: string) => {
  const existingContent = await fs.readFile(filePath, "utf8").catch(() => null);
  if (existingContent === textContent) {
    return false;
  }

  await fs.writeFile(filePath, textContent, "utf8");
  return true;
};

const removeLegacyGeneratedTsxIfPresent = async (entryFilePath: string) => {
  const legacyGeneratedTsxPath = getLegacyGeneratedTsxPath(entryFilePath);
  const legacyContents = await fs
    .readFile(legacyGeneratedTsxPath, "utf8")
    .catch(() => null);

  if (
    !legacyContents?.startsWith("// Generated by pycircuit.") &&
    !legacyContents?.startsWith("// Generated by pycircuits.")
  ) {
    return false;
  }

  await fs.rm(legacyGeneratedTsxPath, { force: true });
  return true;
};

const formatChangedFiles = (changedFiles: string[]) => {
  if (changedFiles.length === 0) {
    return "Python file changes";
  }

  if (changedFiles.length <= 3) {
    return changedFiles.join(", ");
  }

  return `${changedFiles.slice(0, 3).join(", ")} +${changedFiles.length - 3} more`;
};

const getChangedPythonFiles = (
  previousSnapshot: Map<string, number>,
  nextSnapshot: Map<string, number>,
) => {
  const changedFiles = new Set<string>();

  for (const [filePath, modifiedAt] of nextSnapshot.entries()) {
    if (previousSnapshot.get(filePath) !== modifiedAt) {
      changedFiles.add(filePath);
    }
  }

  for (const filePath of previousSnapshot.keys()) {
    if (!nextSnapshot.has(filePath)) {
      changedFiles.add(filePath);
    }
  }

  return Array.from(changedFiles).sort((left, right) =>
    left.localeCompare(right),
  );
};

const collectPythonFileSnapshot = async (rootDir: string) => {
  const snapshot = new Map<string, number>();

  const walk = async (currentDir: string) => {
    const entries = await fs.readdir(currentDir, { withFileTypes: true });

    for (const entry of entries) {
      const absolutePath = path.join(currentDir, entry.name);

      if (entry.isDirectory()) {
        if (!shouldSkipDirectory(entry.name)) {
          await walk(absolutePath);
        }
        continue;
      }

      if (!entry.isFile() || !entry.name.endsWith(".py")) {
        continue;
      }

      const stats = await fs.stat(absolutePath).catch(() => null);
      if (!stats) {
        continue;
      }

      snapshot.set(path.relative(rootDir, absolutePath), stats.mtimeMs);
    }
  };

  await walk(rootDir);
  return snapshot;
};

const discoverPythonEntrypoints = async (rootDir: string) => {
  const entryFilePaths: string[] = [];

  const walk = async (currentDir: string) => {
    const entries = await fs.readdir(currentDir, { withFileTypes: true });
    const entryNames = new Set(
      entries.filter((entry) => entry.isFile()).map((entry) => entry.name),
    );

    for (const candidate of DEFAULT_ENTRYPOINTS) {
      if (entryNames.has(candidate)) {
        entryFilePaths.push(path.join(currentDir, candidate));
        break;
      }
    }

    for (const entry of entries) {
      if (entry.isDirectory() && !shouldSkipDirectory(entry.name)) {
        await walk(path.join(currentDir, entry.name));
      }
    }
  };

  await walk(rootDir);
  return entryFilePaths.sort((left, right) => left.localeCompare(right));
};

const resolveStartTarget = async ({
  inputPath = DEFAULT_START_TARGET,
  cwd = process.cwd(),
}: StartPythonDevServerOptions = {}): Promise<StartTarget> => {
  const absolutePath = path.resolve(cwd, inputPath);
  const stats = await fs.stat(absolutePath).catch(() => null);

  if (!stats) {
    throw new Error(`Start target does not exist: ${inputPath}`);
  }

  if (stats.isDirectory()) {
    return {
      entryFilePaths: [],
      projectDir: absolutePath,
      watchRoot: absolutePath,
    };
  }

  if (!absolutePath.endsWith(".py")) {
    throw new Error(`Start target must be a directory or Python entrypoint: ${inputPath}`);
  }

  return {
    entryFilePaths: [absolutePath],
    projectDir: path.dirname(absolutePath),
    watchRoot: path.dirname(absolutePath),
  };
};

const ensureGeneratedPythonLibrary = async (projectRoot: string) => {
  const generatedRuntimePath = path.join(
    projectRoot,
    "generated",
    "python",
    "pycircuits",
    "runtime.py",
  );

  if (await fileExists(generatedRuntimePath)) {
    return;
  }

  console.log("[pycircuit] Generating Python bindings...");
  const result = await generatePythonLibrary({
    outputDir: path.join(projectRoot, "generated", "python"),
  });
  console.log(
    `[pycircuit] Generated ${result.componentCount} wrappers in ${getRelativePath(result.packageDir)}`,
  );
};

const syncGeneratedTsxFiles = async (
  target: StartTarget,
): Promise<SyncedGeneratedCircuit[]> => {
  const entryFilePaths =
    target.entryFilePaths.length > 0
      ? [...target.entryFilePaths]
      : await discoverPythonEntrypoints(target.projectDir);

  if (entryFilePaths.length === 0) {
    throw new Error(
      `No Python circuit entrypoints found in ${getRelativePath(target.projectDir)}. Expected files named ${DEFAULT_ENTRYPOINTS.join(", ")}.`,
    );
  }

  const syncedCircuits: SyncedGeneratedCircuit[] = [];
  const failures: string[] = [];

  for (const entryFilePath of entryFilePaths) {
    try {
      const renderedCircuit = await renderPythonCircuit({
        inputPath: entryFilePath,
      });
      const generatedTsxPath = getGeneratedTsxPath(renderedCircuit.entryFilePath);
      const removedLegacyFile = await removeLegacyGeneratedTsxIfPresent(
        renderedCircuit.entryFilePath,
      );
      const didWriteFile = await writeTextFileIfChanged(
        generatedTsxPath,
        renderedCircuit.tsxSource,
      );

      if (removedLegacyFile) {
        console.log(
          `[pycircuit] Removed ${getRelativePath(getLegacyGeneratedTsxPath(renderedCircuit.entryFilePath))}`,
        );
      }

      console.log(
        `[pycircuit] ${didWriteFile ? "Updated" : "Verified"} ${getRelativePath(generatedTsxPath)} from ${getRelativePath(renderedCircuit.entryFilePath)}`,
      );

      syncedCircuits.push({
        entryFilePath: renderedCircuit.entryFilePath,
        generatedTsxPath,
        selectedSymbol: renderedCircuit.selectedSymbol,
      });
    } catch (error) {
      failures.push(
        `${getRelativePath(entryFilePath)}: ${error instanceof Error ? error.message : String(error)}`,
      );
    }
  }

  for (const failure of failures) {
    console.error(`[pycircuit] ${failure}`);
  }

  if (syncedCircuits.length === 0) {
    throw new Error("Failed to build any Python circuits for the dev server.");
  }

  return syncedCircuits.sort((left, right) =>
    left.generatedTsxPath.localeCompare(right.generatedTsxPath),
  );
};

const isPortAvailable = (port: number) =>
  new Promise<boolean>((resolve) => {
    const server = net.createServer();
    server.once("error", () => resolve(false));
    server.once("listening", () => {
      server.close(() => resolve(true));
    });
    server.listen(port);
  });

const getAvailablePort = async (preferredPort: number) => {
  let port = preferredPort;

  while (!(await isPortAvailable(port))) {
    console.log(`[pycircuit] Port ${port} is in use, trying ${port + 1}...`);
    port += 1;
  }

  return port;
};

export async function startPythonDevServer({
  cwd = process.cwd(),
  inputPath = DEFAULT_START_TARGET,
  port = DEFAULT_DEV_SERVER_PORT,
}: StartPythonDevServerOptions = {}): Promise<PythonDevServerHandle> {
  const target = await resolveStartTarget({ cwd, inputPath });
  const projectRoot = await findProjectRoot(target.projectDir);

  await ensureGeneratedPythonLibrary(projectRoot);

  let syncedCircuits = await syncGeneratedTsxFiles(target);
  const defaultCircuit = syncedCircuits[0];
  if (!defaultCircuit) {
    throw new Error("Failed to determine a default generated circuit for the dev server.");
  }

  const resolvedPort = await getAvailablePort(port);
  const server = new DevServer({
    port: resolvedPort,
    componentFilePath: defaultCircuit.generatedTsxPath,
    projectDir: target.projectDir,
  });

  await server.start();

  const relativeMainComponentPath = path
    .relative(target.projectDir, defaultCircuit.generatedTsxPath)
    .replaceAll(path.sep, "/");

  console.log("");
  console.log(`[pycircuit] Dev server ready at http://localhost:${resolvedPort}/#file=${encodeURIComponent(relativeMainComponentPath)}`);
  console.log(
    `[pycircuit] Watching ${getRelativePath(target.watchRoot)} for Python changes...`,
  );

  let stopped = false;
  let scanInProgress = false;
  let rebuildInProgress = false;
  let rebuildTimer: ReturnType<typeof setTimeout> | null = null;
  let pendingRebuildReason = "Python file changes";
  let rerunRequested = false;
  let pythonSnapshot = await collectPythonFileSnapshot(target.watchRoot);

  const runRebuild = async () => {
    if (stopped) {
      return;
    }

    if (rebuildInProgress) {
      rerunRequested = true;
      return;
    }

    rebuildInProgress = true;

    try {
      syncedCircuits = await syncGeneratedTsxFiles(target);
      if (syncedCircuits.length > 0) {
        console.log("[pycircuit] Rebuild complete.");
      }
    } catch (error) {
      console.error(
        `[pycircuit] Rebuild failed: ${error instanceof Error ? error.message : String(error)}`,
      );
    } finally {
      rebuildInProgress = false;

      if (rerunRequested && !stopped) {
        rerunRequested = false;
        scheduleRebuild("queued changes");
      }
    }
  };

  const scheduleRebuild = (reason: string) => {
    pendingRebuildReason = reason;

    if (rebuildTimer) {
      clearTimeout(rebuildTimer);
    }

    rebuildTimer = setTimeout(() => {
      rebuildTimer = null;
      console.log(`[pycircuit] Rebuilding after ${pendingRebuildReason}...`);
      void runRebuild();
    }, REBUILD_DEBOUNCE_MS);
  };

  const scanForPythonChanges = async () => {
    if (stopped || scanInProgress) {
      return;
    }

    scanInProgress = true;

    try {
      const nextSnapshot = await collectPythonFileSnapshot(target.watchRoot);
      const changedFiles = getChangedPythonFiles(pythonSnapshot, nextSnapshot);

      if (changedFiles.length > 0) {
        pythonSnapshot = nextSnapshot;
        scheduleRebuild(formatChangedFiles(changedFiles));
      }
    } catch (error) {
      console.error(
        `[pycircuit] Failed to scan Python files: ${error instanceof Error ? error.message : String(error)}`,
      );
    } finally {
      scanInProgress = false;
    }
  };

  const scanInterval = setInterval(() => {
    void scanForPythonChanges();
  }, PYTHON_SCAN_INTERVAL_MS);

  const stop = async () => {
    if (stopped) {
      return;
    }

    stopped = true;

    clearInterval(scanInterval);
    if (rebuildTimer) {
      clearTimeout(rebuildTimer);
      rebuildTimer = null;
    }

    await server.stop();
  };

  return {
    componentFilePath: defaultCircuit.generatedTsxPath,
    port: resolvedPort,
    projectDir: target.projectDir,
    stop,
  };
}
